def main() -> None:
    doc = json.loads(PATH.read_text(encoding="utf-8"))
    styles = doc["styles"]
    by_name = {s["style_name"]: s for s in styles}
    filled = 0
    for name, (use_when, pitfalls) in B.items():
        s = by_name.get(name)
        if s is None:
            raise SystemExit(f"B 表风格名与 json 不匹配：{name}")
        s["use_when"], s["pitfalls"] = use_when, pitfalls
        filled += 1
    for s in A:
        if s["style_name"] in by_name:
            by_name[s["style_name"]].update(s)   # 幂等重跑：覆盖同名
        else:
            styles.append(s)
    PATH.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    print(f"B 补齐 {filled} 条；A 追加/更新 {len(A)} 条；总计 {len(styles)} 条")


if __name__ == "__main__":
    main()
