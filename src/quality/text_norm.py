# 映射对两侧同向：规范字本身映射到自身（幂等），无需反向表

_WS_RE = re.compile(r"\s+")


def normalize_text(s: str) -> str:
    """归一化：繁简/异体字映射 → 全半角统一 → 去空白。"""
    out = []
    for ch in s or "":
        ch = TRAD2SIMP.get(ch, ch)
        code = ord(ch)
        if code == 0x3000:          # 全角空格 → 半角（随后被去空白剔除）
            ch = " "
        elif 0xFF01 <= code <= 0xFF5E:   # 全角 ASCII（含数字/字母/标点）→ 半角
            ch = chr(code - 0xFEE0)
        out.append(ch)
    return _WS_RE.sub("", "".join(out))


def texts_equal_exact(ocr_text: str, page_copy: str) -> bool:
    """100% 标准：双方归一化后逐字完全相等；文案本就无字（归一化为空）算通过。"""
    a, b = normalize_text(ocr_text), normalize_text(page_copy)
    if not b:
        return True
    if not a:
        return False
    return a == b
